// Generate TypeScript types from the JSON Schemas exported by packages/contracts.
// The schemas are the single source of truth; never edit src/contracts by hand.
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { compile } from 'json-schema-to-typescript';
import prettier from 'prettier';

const here = dirname(fileURLToPath(import.meta.url));
const schemaDir = join(here, '../../../packages/contracts/schema');
const outDir = join(here, '../src/contracts');

const SCHEMAS = [
  'Zone',
  'CameraConfig',
  'Rule',
  'AlertEvent',
  'DeviceStatus',
  'Metrics',
  'StaffSuggestion',
];

const BANNER =
  '/* Generated by `npm run contracts` from packages/contracts/schema. Do not edit. */';

const prettierConfig = (await prettier.resolveConfig(join(outDir, 'x.ts'))) ?? {};

// json-schema-to-typescript does not understand draft 2020-12 `prefixItems`;
// rewrite it to the equivalent draft-07 tuple form so points become [number, number].
function normalise(node) {
  if (Array.isArray(node)) return node.map(normalise);
  if (node && typeof node === 'object') {
    const out = {};
    for (const [key, value] of Object.entries(node)) {
      if (key === 'prefixItems') out.items = normalise(value);
      else out[key] = normalise(value);
    }
    if ('prefixItems' in node && 'items' in node) out.items = normalise(node.prefixItems);
    return out;
  }
  return node;
}

await mkdir(outDir, { recursive: true });
for (const name of SCHEMAS) {
  const raw = JSON.parse(await readFile(join(schemaDir, `${name}.json`), 'utf8'));
  const ts = await compile(normalise(raw), name, {
    bannerComment: BANNER,
    additionalProperties: false,
    format: false,
    strictIndexSignatures: true,
  });
  const formatted = await prettier.format(ts, { ...prettierConfig, parser: 'typescript' });
  await writeFile(join(outDir, `${name}.ts`), formatted);
}
// Zone is also inlined in CameraConfig; export the canonical names explicitly to avoid clashes.
const indexSrc = [
  BANNER,
  "export type { Zone } from './Zone';",
  "export type { CameraConfig } from './CameraConfig';",
  "export type { Rule, Condition, Action } from './Rule';",
  "export type { AlertEvent } from './AlertEvent';",
  "export type { DeviceStatus } from './DeviceStatus';",
  "export type { Metrics } from './Metrics';",
  "export type { StaffSuggestion } from './StaffSuggestion';",
  '',
].join('\n');
await writeFile(
  join(outDir, 'index.ts'),
  await prettier.format(indexSrc, { ...prettierConfig, parser: 'typescript' }),
);
console.log(`contracts: wrote ${SCHEMAS.length} types to src/contracts`);
